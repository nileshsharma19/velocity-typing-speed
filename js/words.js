/**
 * Generate randomized word sequence
 * @param {number} count 
 * @param {boolean} withPunctuation 
 * @param {boolean} withNumbers 
 * @returns {string[]}
 */
export function generateWords(count = 25, withPunctuation = false, withNumbers = false) {
  const words = [];
  const bank = wordBanks.common200;

  for (let i = 0; i < count; i++) {
    // 12% chance to insert a number if enabled
    if (withNumbers && Math.random() < 0.12) {
      const num = Math.floor(Math.random() * 900) + 10;
      words.push(num.toString());
      continue;
    }

    let word = bank[Math.floor(Math.random() * bank.length)];

    if (withPunctuation) {
      // Capitalize first letter of sentence
      if (i === 0 || words[i - 1]?.match(/[.!?]$/)) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }

      // Add random punctuation
      const pRand = Math.random();
      if (pRand < 0.15) {
        word += ",";
      } else if (pRand < 0.28) {
        word += ".";
      } else if (pRand < 0.32) {
        word += "?";
      } else if (pRand < 0.36) {
        word += "!";
      } else if (pRand < 0.40) {
        word = `"${word}"`;
      }
    }

    words.push(word);
  }

  // Ensure last word has proper sentence end if punctuation enabled
  if (withPunctuation && words.length > 0) {
    let last = words[words.length - 1];
    if (!last.match(/[.!?]$/)) {
      words[words.length - 1] = last + ".";
    }
  }

  return words;
}

/**
 * Get a random quote
 * @param {string} lengthFilter ('all' | 'short' | 'medium' | 'long')
 * @returns {{text: string, author: string}}
 */
export function getRandomQuote(lengthFilter = "all") {
  let list = wordBanks.quotes;
  if (lengthFilter !== "all") {
    list = list.filter(q => q.length === lengthFilter);
    if (list.length === 0) list = wordBanks.quotes;
  }
  return list[Math.floor(Math.random() * list.length)];
}

/**
 * Get a random code snippet
 * @param {string} language ('javascript' | 'python' | 'html')
 * @returns {string}
 */
export function getRandomCodeSnippet(language = "javascript") {
  const snippets = wordBanks.code[language] || wordBanks.code.javascript;
  return snippets[Math.floor(Math.random() * snippets.length)];
}
